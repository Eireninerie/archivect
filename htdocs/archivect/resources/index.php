<h1 >RESOURCES</h1>
<h3>Links for Learning</h3>
<p>At some point I intend to turn this into a fully-fledged searchable directory, because I have many more. Until then, here's some starters</p>
<h3>General Architecture</h3>
<ul>
    <li><b>Architects directory:</b> <a href="https://architectdirectory.co.uk/">The Architect Directory</a><br> This came out while I was making this database. It's much larger than this one but it is specific to housing and landscapes. I think it is tailored towards clients rather than students. It's similar in some respects to <a href="https://www.houzz.co.uk/professionals/architects-and-building-designers/">houzz</a>, if a little fancier.</a></li>
    <li><b>Case Studies:</b> <a href="https://divisare.com/">Divisare</a></br> A student-focused list of global case studies</li>

</ul>
<h3>Open source and legally free software</h3>
<span>Instead of paying an arm and a leg for software, or for some reason using Sketchup (heaven help us), consider the following:</span>
<ul>
    <li><b>Sketching/painting:</b> <a href="https://krita.org/en/">Krita</a><br>One of the very best pieces of software out there for drawing. And I don't mean best of affordable, I mean best of all: the brushes and tools are great. That said, it's a little basic for photo editing.</li>
    <li><b>Design:</b> <a href="https://inkscape.org/">Inkscape</a><br>It's a little like Adobe Illustrator I guess. I use it to take apart cad drawings and pdfs or for simple icons and annotations.</li>
    <li><b>CAD:</b> <a href="https://www.freecad.org/">FreeCAD</a><br>Not as powerful as Autocad or Revit, which you can get a free student license for, but good for the fundamentals and means you're not locked in to subscriptions.</li>
<li><b>Presentations/ publishing/ documents:</b> <a href="https://www.affinity.studio/">Affinity</a><br> Not open source, but a genuine legally free competitor to InDesign. No reason to still use Powerpoint.</li>
<li><b>General 3D:</b> <a href="https://www.blender.org/download/">Blender</a> When I say blender can do everything, I mean it. but it is a bit steep to learn.</a>
</ul>
<h3>Other</h3>
<ul>
    <li><b>Magazine</b>: <a href="https://www.theplan.it/eng/theplan-free">The Plan</a><br> The plan has a main page and subscription, but sometimes it'll provide free copies of past issues through this link. To save parts of the free digital magazine, press print and select a few articles at a time. (it doesn't like 'printing' the whole thing in one go).</li>
    <li><b>Tectonics</b>: <a href="https://www.instagram.com/the_donnies/">The Donnies</a></br>Facade details instagram</li>
    <li><b>Accessibility</b>: <a href="https://wellcomecollection.org/stories/exploring-deaf-space-at-london-college-of-fashion">"Deaf Space"</a><br> Chris Laing heads up the <a href="https://www.deafarchitecturefront.com/">Deaf Architecture Front</a>. The talk he did at the launch was enlightening. He also consulted on a recent DIY SOS.</li>
    <li><b>Substainability / Tectonics</b>: <a href="https://www.naturaldetailslibrary.org/">The Natural Materials Library</a><br>An ACAN project on sustainable materials + detailing</li>
    <li><b>Research</b>: <a href="https://archive.org/">Archive.org</a><br> Find books you can't get in the library, old documentaries, and sometimes the backups of websites on the 'waybackmachine' mean you can dodge paywalls.</li>
    <li><b>Context</b>: <a href="http://www.datashine.org.uk"> Datashine</a><br>Demographic data</li>
    <li><b>Theory</b>: <a href="https://www.spatialagency.net/database/"> Spatial Agency</a><br>An academic database of architectural theory and movements. Absolute goldmine. Beneath each article is a fun digram showing how it's connected to other parts of history or studios etc.</li>
</ul>
